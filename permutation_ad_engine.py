class ModularPermutationEngine:
    """
    محرك التركيب التبادلي اللانهائي
    ينتج إعلانات جذابة، متوازنة، غير متكررة، ومحسوبة الأرقام.
    Total Permutations = 34 * 24 * 18 * 15 = 220,320+ Unique Ads!
    """

    def __init__(self):
        self.hooks = HOOKS
        self.bodies = BODIES
        self.scarcities = SCARCITIES
        self.ctas = CTAS
        self.total_permutations = len(self.hooks) * len(self.bodies) * len(self.scarcities) * len(self.ctas)

    def generate_raw_template(self, seed: Optional[int] = None) -> str:
        """
        يولد قالباً إعلانياً فريداً ومكتمل الأركان.
        يحتوي على فقرة خطاف + قيمة + ندرة + دعوة للعمل.
        مع الحفاظ على مسافات متناسقة وإيموجي مدروس وغير مزدحم.
        """
        rng = random.Random(seed) if seed is not None else random

        hook = rng.choice(self.hooks)
        body = rng.choice(self.bodies)
        scarcity = rng.choice(self.scarcities)
        cta = rng.choice(self.ctas)

        # Structure with clean line breaks
        template = f"{hook}\n\n{body}\n\n{scarcity}\n\n{cta}"
        return template

    def generate_ad(
        self,
        title: str,
        link: str,
        extra_link: Optional[str] = None,
        members_count: Optional[int] = None,
        seed: Optional[int] = None
    ) -> str:
        """
        توليد إعلان جاهز للنشر وتنسيقه مع الروابط والعناوين.
        """
        raw_tmpl = self.generate_raw_template(seed=seed)
        from worker import format_user_template
        return format_user_template(
            template=raw_tmpl,
            title=title,
            link=link,
            extra_link=extra_link,
            members_count=members_count
        )


